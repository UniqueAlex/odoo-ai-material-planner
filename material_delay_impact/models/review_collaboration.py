"""Assignment-scoped collaboration, without granting purchase/stock/MO access.

Only a fully authorized planner can produce a shared calculation. Participants
read that immutable calculation and update their own assigned review only.
No arbitrary business record is read through sudo on a participant's behalf.
"""
from copy import deepcopy
from datetime import datetime, timezone
import json
from urllib.parse import urlencode
from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError
from . import reallocation_adapter, snapshot, review_freshness


class ReviewSharing(models.Model):
    _inherit = 'mail.activity'

    mdic_shared_plan = fields.Json(copy=False, groups='base.group_system')

    def _mdic_inbox_tasks(self, completed=False, activity_id=None):
        if not self.env.user.has_group('base.group_user') or type(completed) is not bool:
            raise AccessError(_('No assigned review is available.'))
        domain = [('res_model', '=', 'purchase.order'), ('mdic_line_id', '!=', False),
                  ('user_id', '=', self.env.uid), ('mdic_decision', '=', False),
                  ('mdic_line_id.company_id', 'in', self.env.companies.ids),
                  ('mdic_shared_plan', '!=', False)]
        if activity_id is not None:
            if type(activity_id) is not int:
                raise AccessError(_('No assigned review is available.'))
            domain.append(('id', '=', activity_id))
        else:
            domain.append(('active', '=', not completed))
        return self.sudo().with_context(active_test=False).search(domain, order='date_deadline, id desc', limit=201)

    @api.model
    @api.readonly
    def mdic_my_reviews(self, completed=False):
        """Only own cached assignments; no native purchase form or financial fields."""
        tasks = self._mdic_inbox_tasks(completed)
        return {'truncated': len(tasks) > 200, 'items': [{
            'id': task.id, 'summary': task.summary or '',
            'order': task.mdic_shared_plan['report']['order'],
            'material': task.mdic_shared_plan['report']['product'],
            'due': fields.Date.to_string(task.date_deadline),
            'done': not task.active, 'outcome': task.mdic_outcome or 'unknown',
            'feedback': task.feedback or ''} for task in tasks[:200]]}

    @api.model
    @api.readonly
    def mdic_open_my_review(self, activity_id):
        # Recheck assignee and company at click time, including after reassignment.
        tasks = self._mdic_inbox_tasks(activity_id=activity_id)
        if len(tasks) != 1:
            raise AccessError(_('This assignment changed. Refresh progress.'))
        task = tasks[0]
        return {'type': 'ir.actions.act_url', 'target': 'self',
                'url': '/odoo/action-material_delay_impact?' + urlencode({
                    'active_id': task.res_id, 'mdic_line': task.mdic_line_id.id,
                    'mdic_arrival': task.mdic_arrival.replace(tzinfo=timezone.utc).isoformat(),
                    'mdic_tz': self.env.user.tz or 'UTC'})}

    @api.model_create_multi
    def create(self, vals_list):
        if any('mdic_shared_plan' in v for v in vals_list) or 'default_mdic_shared_plan' in self.env.context:
            raise AccessError(_('Shared review facts must be generated by the server.'))
        records = super().create(vals_list)
        for task in records.filtered(lambda t: t.mdic_line_id and not t.mdic_decision):
            snapshot.check_scope(self.env)
            order, line = task.mdic_line_id.order_id, task.mdic_line_id
            arrival = task.mdic_arrival.replace(tzinfo=timezone.utc).isoformat()
            value = order._mdic_read(lambda env: reallocation_adapter.request(env, order.id, line.id, arrival, recommend=True))
            option = next((o for o in value['automatic']['alternatives'] if o['review_key'] == task.mdic_option_key), None)
            if (value['review_revision'] != task.mdic_revision or not option or
                    not any(t['key'] == task.mdic_target_key and t['role'] == task.mdic_role for t in option['review_targets'])):
                raise UserError(_('The review scenario changed. Analyze again.'))
            if task.user_id.share or not task.user_id.active or line.company_id not in task.user_id.company_ids:
                raise UserError(_('Assign an internal user who can access this company.'))
            # Deliberately share only the assigned candidate and the same-material
            # calculation. Adapter output contains no price, partner or secrets.
            payload = {k: deepcopy(value[k]) for k in ('report', 'automatic', 'review_revision')}
            payload['freshness_stamp'] = review_freshness.stamp(line)
            payload['automatic']['alternatives'] = [deepcopy(option)]
            payload['ai_recommendation'] = {'status': 'not_requested'}
            super(ReviewSharing, task.sudo()).write({'mdic_shared_plan': payload})
        return records

    def write(self, vals):
        if 'mdic_shared_plan' in vals:
            raise AccessError(_('Shared review facts cannot be edited.'))
        identity = {'mdic_line_id', 'mdic_option_key', 'mdic_target_key', 'mdic_revision', 'mdic_arrival', 'mdic_role', 'res_model_id', 'res_id'}
        if identity.intersection(vals) and any(t.sudo().mdic_shared_plan for t in self):
            raise AccessError(_('Create a new review for a different scenario.'))
        if 'user_id' in vals:
            owner = self.env['res.users'].sudo().browse(vals['user_id']).exists()
            for task in self.sudo().filtered('mdic_shared_plan'):
                if len(owner) != 1 or owner.share or not owner.active or task.mdic_line_id.company_id not in owner.company_ids:
                    raise UserError(_('Assign an internal user who can access this company.'))
        return super().write(vals)


class ReviewCollaboration(models.Model):
    _inherit = 'purchase.order'

    mdic_can_open_plan = fields.Boolean(compute='_compute_mdic_can_open_plan')

    @api.depends_context('uid', 'allowed_company_ids')
    def _compute_mdic_can_open_plan(self):
        planner = all(self.env.user.has_group(g) for g in ('purchase.group_purchase_user', 'stock.group_stock_user', 'mrp.group_mrp_user'))
        for order in self:
            if planner:
                order.mdic_can_open_plan = order.state in ('purchase', 'done')
            else:
                try:
                    order.mdic_can_open_plan = bool(order._mdic_shared_tasks(None))
                except AccessError:
                    order.mdic_can_open_plan = False

    @api.readonly
    def action_mdic_common_plan(self):
        self.ensure_one()
        if all(self.env.user.has_group(g) for g in ('purchase.group_purchase_user', 'stock.group_stock_user', 'mrp.group_mrp_user')):
            return self.action_material_delay()
        tasks = self._mdic_shared_tasks(None)
        return tasks[0].with_user(self.env.user).action_mdic_open_plan()

    def mdic_publish_reviews(self, line_id, arrival):
        """Upgrade legacy assignments only when today's exact facts still match.

        A planner's explicit page refresh publishes the current calculation;
        participants never trigger a privileged calculation or a backfill.
        """
        self._mdic_review_line(line_id)
        tasks = self.env['mail.activity'].with_context(active_test=False).search([
            ('res_model', '=', 'purchase.order'), ('res_id', '=', self.id),
            ('mdic_line_id', '=', line_id), ('mdic_decision', '=', False)], limit=201)
        if len(tasks) > 200:
            return 0
        tasks = tasks.filtered(lambda t: not t.sudo().mdic_shared_plan)
        if not tasks:
            return 0
        value = self._mdic_read(lambda env: reallocation_adapter.request(env, self.id, line_id, arrival, recommend=True))
        count = 0
        for task in tasks.filtered(lambda t: t.mdic_revision == value['review_revision']):
            option = next((o for o in value['automatic']['alternatives'] if o['review_key'] == task.mdic_option_key), None)
            if (not option or task.user_id.share or not task.user_id.active or
                    task.mdic_line_id.company_id not in task.user_id.company_ids or
                    not any(t['key'] == task.mdic_target_key and t['role'] == task.mdic_role for t in option['review_targets'])):
                continue
            payload = {k: deepcopy(value[k]) for k in ('report', 'automatic', 'review_revision')}
            payload['freshness_stamp'] = review_freshness.stamp(task.mdic_line_id)
            payload['automatic']['alternatives'] = [deepcopy(option)]
            payload['ai_recommendation'] = {'status': 'not_requested'}
            # Adding a calculation cache must not make old feedback appear new
            # or change the author/date of its existing review audit fields.
            task.flush_recordset(['mdic_shared_plan'])
            self.env.cr.execute(
                'UPDATE mail_activity SET mdic_shared_plan=%s::jsonb WHERE id=%s AND mdic_shared_plan IS NULL',
                [json.dumps(payload), task.id])
            count += self.env.cr.rowcount
            task.invalidate_recordset(['mdic_shared_plan'])
        return count

    def _mdic_shared_tasks(self, line_id, arrival=None):
        self.ensure_one()
        if (line_id is not None and type(line_id) is not int) or not self.env.user.has_group('base.group_user'):
            raise AccessError(_('No assigned review is available.'))
        domain = [('res_model', '=', 'purchase.order'), ('res_id', '=', self.id),
                  ('mdic_line_id', '!=', False), ('user_id', '=', self.env.uid),
                  ('mdic_line_id.company_id', 'in', self.env.companies.ids), ('mdic_decision', '=', False)]
        if line_id is not None:
            domain.append(('mdic_line_id', '=', line_id))
        if arrival is not None:
            try:
                at = datetime.fromisoformat(arrival)
                if not at.tzinfo: raise ValueError()
                at = at.astimezone(timezone.utc).replace(tzinfo=None)
            except (ValueError, TypeError):
                raise AccessError(_('No assigned review is available.')) from None
            domain.append(('mdic_arrival', '=', at))
        # Native mail.activity ACLs depend on access to the parent purchase. This
        # narrow query authorizes explicit assignee + allowed company first.
        tasks = self.env['mail.activity'].sudo().with_context(active_test=False).search(domain, order='id desc', limit=200)
        tasks = tasks.filtered('mdic_shared_plan')
        if not tasks:
            raise AccessError(_('No assigned review is available. Ask the planner to assign a current review.'))
        return tasks

    @api.readonly
    def mdic_collaboration(self, line_id=None, arrival=None):
        if all(self.env.user.has_group(g) for g in ('purchase.group_purchase_user', 'stock.group_stock_user', 'mrp.group_mrp_user')):
            return False
        tasks = self._mdic_shared_tasks(line_id, arrival)
        payload = deepcopy(tasks[0].mdic_shared_plan)
        payload.pop('freshness_stamp', None)
        payload['shared_line_id'] = tasks[0].mdic_line_id.id
        options = {}
        for task in tasks.filtered(lambda t: t.mdic_revision == tasks[0].mdic_revision):
            for option in task.mdic_shared_plan['automatic']['alternatives']:
                options.setdefault(option['review_key'], deepcopy(option))
        payload['automatic']['alternatives'] = list(options.values())
        return payload

    @api.readonly
    def mdic_shared_progress(self, line_id, arrival):
        assigned = self._mdic_shared_tasks(line_id, arrival)
        anchor = assigned[0]
        current_stamp = review_freshness.stamp(anchor.mdic_line_id)
        freshness = review_freshness.status(anchor.mdic_shared_plan.get('freshness_stamp'), current_stamp)
        keys = assigned.filtered(lambda t: t.mdic_revision == anchor.mdic_revision).mapped('mdic_option_key')
        tasks = self.env['mail.activity'].sudo().with_context(active_test=False).search([
            ('res_model', '=', 'purchase.order'), ('res_id', '=', self.id), ('mdic_line_id', '=', line_id),
            ('mdic_revision', '=', anchor.mdic_revision), ('mdic_option_key', 'in', keys)],
            order='id desc', limit=201)
        return {'freshness': freshness, 'truncated': len(tasks) > 200, 'tasks': [{
            'id': t.id, 'option_key': t.mdic_option_key, 'target_key': t.mdic_target_key,
            'revision': t.mdic_revision, 'arrival': fields.Datetime.to_string(t.mdic_arrival),
            'role': t.mdic_role, 'summary': t.summary or '', 'owner': t.user_id.display_name or '',
            'assigned_to_me': t.user_id.id == self.env.uid,
            'due': fields.Date.to_string(t.date_deadline), 'done': not t.active,
            'updated': fields.Datetime.to_string(t.write_date), 'feedback': t.feedback or '',
            'outcome': t.mdic_outcome or 'unknown', 'decision': t.mdic_decision or '',
            'can_feedback': freshness == 'unchanged' and t.active and t.user_id.id == self.env.uid and not t.mdic_decision,
            'facts_stale': freshness != 'unchanged'
        } for t in tasks[:200]]}

    def mdic_shared_feedback(self, line_id, arrival, activity_id, outcome, feedback):
        if type(activity_id) is not int or outcome not in ('unknown', 'met', 'not_met') or not isinstance(feedback, str) or not 1 <= len(feedback.strip()) <= 2000:
            raise UserError(_('Enter a conclusion and feedback (maximum 2000 characters).'))
        tasks = self._mdic_shared_tasks(line_id, arrival)
        task = tasks.filtered(lambda t: t.id == activity_id and t.active)
        if len(task) != 1:
            raise AccessError(_('Only your pending assigned review can be completed.'))
        self.env.cr.execute('SELECT id FROM mail_activity WHERE id=%s FOR UPDATE', [task.id])
        task.invalidate_recordset()
        if not task.active or task.user_id.id != self.env.uid:
            raise AccessError(_('This assignment changed. Refresh progress.'))
        if review_freshness.status(task.mdic_shared_plan.get('freshness_stamp'), review_freshness.stamp(task.mdic_line_id)) != 'unchanged':
            raise UserError(_('Business records changed or cannot be checked. Ask the planner to analyze and assign again. Previous feedback is retained as history.'))
        task.write({'mdic_outcome': outcome, 'feedback': feedback.strip()})
        task.action_mdic_complete()
        return True
